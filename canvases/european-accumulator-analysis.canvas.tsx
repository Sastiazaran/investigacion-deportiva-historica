const SEASON_RECORDS: SeasonRecord[] = SEASON_ROWS.map(
  ([club, season, league, played, won, drawn, lost]) => ({
    club,
    season,
    league,
    played,
    won,
    drawn,
    lost,
  }),
);

const MIN_YEAR = 2000;
const MAX_YEAR = 2025;
/** Chart stays readable; full club list is in the table. */
const CHART_TOP_N = 20;
const COMBO_TOP_N = 10;

const TIER_S_MIN = 57; // S >= 57%
const TIER_A_MIN = 43; // A >= 43% and < 57%

function clamp(n: number, min: number, max: number) {
  return Math.max(min, Math.min(max, n));
}

function tierFromWinPct(winPct: number): Tier {
  if (winPct >= TIER_S_MIN) return "S";
  if (winPct >= TIER_A_MIN) return "A";
  return "B";
}

function formatSeasonPart(startYear: number) {
  const endYear = startYear + 1;
  return `${startYear}/${String(endYear).slice(-2)}`;
}

function formatPeriodLabel(startYear: number, endYear: number) {
  return `Seasons ${formatSeasonPart(startYear)} – ${formatSeasonPart(endYear)}`;
}

function formatOdds(probability: number) {
  if (probability <= 0) return "—";
  const approxDecimal = 1 / probability;
  return `${approxDecimal.toFixed(1)}:1`;
}

function makeComboTierLabel(tiers: Tier[]) {
  const counts = { S: 0, A: 0, B: 0 } as Record<Tier, number>;
  for (const t of tiers) counts[t] += 1;
  const parts: string[] = [];
  if (counts.S) parts.push(`S${counts.S > 1 ? `x${counts.S}` : ""}`);
  if (counts.A) parts.push(`A${counts.A > 1 ? `x${counts.A}` : ""}`);
  if (counts.B) parts.push(`B${counts.B > 1 ? `x${counts.B}` : ""}`);
  return parts.length ? parts.join("+") : "—";
}

function generateCombinations<T>(items: T[], size: number) {
  const result: T[][] = [];
  const n = items.length;
  if (size <= 0 || size > n) return result;

  const indices = Array.from({ length: size }, (_, i) => i);
  while (true) {
    result.push(indices.map((i) => items[i]));
    let i = size - 1;
    while (i >= 0 && indices[i] === n - size + i) i--;
    if (i < 0) break;
    indices[i]++;
    for (let j = i + 1; j < size; j++) {
      indices[j] = indices[j - 1] + 1;
    }
  }
  return result;
}

