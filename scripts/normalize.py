ALIASES: dict[str, str] = {}
for _canonical, _aliases in _GROUPS:
    for _alias in _aliases:
        ALIASES[_alias.lower()] = _canonical

_PREFIXES = ("fc ", "afc ", "ac ", "as ", "cf ", "cd ", "sc ", "ud ", "ssc ", "rcd ")
_SUFFIXES = (
    " fc",
    " afc",
    " cf",
    " sc",
    " ud",
    " cd",
    " ac",
    " bk",
    " sk",
    " balompié",
    " de fútbol",
)


def _lookup_candidates(name: str) -> list[str]:
    candidates = [name]
    lower = name.lower()
    for prefix in _PREFIXES:
        if lower.startswith(prefix):
            candidates.append(name[len(prefix) :].strip())
    for suffix in _SUFFIXES:
        if lower.endswith(suffix):
            candidates.append(name[: -len(suffix)].strip())
    return candidates


def normalize_team(name: str | None) -> str | None:
    """Return the canonical club label, or None when the source name is empty."""
    if not name:
        return None
    cleaned = " ".join(str(name).strip().split())
    if not cleaned:
        return None
    for candidate in _lookup_candidates(cleaned):
        hit = ALIASES.get(candidate.lower())
        if hit:
            return hit
    stripped = cleaned
    lower = cleaned.lower()
    for suffix in _SUFFIXES:
        if lower.endswith(suffix):
            stripped = cleaned[: -len(suffix)].strip()
            break
    return stripped or cleaned


def club_slug(name: str) -> str:
    """URL slug. Must stay in lockstep with web/src/lib/metrics.ts clubSlug."""
    folded = unicodedata.normalize("NFKD", name)
    folded = "".join(ch for ch in folded if not unicodedata.combining(ch))
    folded = folded.lower()
    folded = re.sub(r"[^a-z0-9]+", "-", folded).strip("-")
    return folded
